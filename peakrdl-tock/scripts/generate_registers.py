"""Generate registers/generated-firmware-peakrdl from the SoC and MCU address maps.

Each addrmap instantiated in the top-level maps becomes one Rust module, at
the address it has in the map.

    python peakrdl-tock/scripts/generate_registers.py          # write the files
    python peakrdl-tock/scripts/generate_registers.py --check  # verify they are current
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

from systemrdl import RDLCompiler
from systemrdl.node import AddrmapNode

from peakrdl_tock import TockExporter

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEST_DIR = PROJECT_ROOT / "registers" / "generated-firmware-peakrdl" / "src"

I3C_RDL = "hw/caliptra-ss/third_party/i3c-core/src/rdl/registers.rdl"

# (top addrmap, RDL files to compile in order)
ADDRESS_MAPS = [
    ("soc", ["hw/caliptra-ss/src/integration/rtl/soc_address_map.rdl"]),
    ("mcu", [I3C_RDL, "hw/mcu.rdl"]),
]

# Instances that are not exported. I3CCSR1 has the same registers as I3CCSR.
SKIP_INSTANCES = {"I3CCSR1"}

HEADER = "// Licensed under the Apache-2.0 license\n// Generated by peakrdl-tock\n\n"


def generate(dest: Path) -> None:
    """Write one module per addrmap instance, and lib.rs, to dest."""
    dest.mkdir(parents=True, exist_ok=True)
    exporter = TockExporter()
    modules = []
    for top, rdl_files in ADDRESS_MAPS:
        rdlc = RDLCompiler()
        for rdl_file in rdl_files:
            rdlc.compile_file(str(PROJECT_ROOT / rdl_file))
        root = rdlc.elaborate(top_def_name=top)
        for child in root.top.children():
            if not isinstance(child, AddrmapNode) or child.inst_name in SKIP_INSTANCES:
                continue
            exporter.export(child, str(dest), header=HEADER)
            modules.append(child)

    names = sorted(p.stem for p in dest.glob("*.rs") if p.name != "lib.rs")
    if len(names) != len(modules):
        raise RuntimeError(f"expected {len(modules)} modules in {dest}, found {names}")
    lib = HEADER + '#![no_std]\n#![recursion_limit = "2048"]\n\n'
    lib += "".join(f"pub mod {name};\n" for name in names)
    (dest / "lib.rs").write_text(lib)


def check(dest: Path) -> bool:
    """Return whether dest matches freshly generated output."""
    with tempfile.TemporaryDirectory() as tmp:
        generate(Path(tmp))
        fresh = {p.name: p.read_text() for p in Path(tmp).glob("*.rs")}
    current = {p.name: p.read_text() for p in dest.glob("*.rs")}
    stale = sorted(name for name in fresh.keys() | current.keys() if fresh.get(name) != current.get(name))
    for name in stale:
        print(f"{dest / name} does not match the generator output", file=sys.stderr)
    return not stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check that the generated files are current instead of writing them.",
    )
    args = parser.parse_args()
    if args.check:
        if not check(DEST_DIR):
            print(f"Run {Path(__file__).relative_to(PROJECT_ROOT)} to update.", file=sys.stderr)
            return 1
        return 0
    generate(DEST_DIR)
    return 0


if __name__ == "__main__":
    sys.exit(main())
