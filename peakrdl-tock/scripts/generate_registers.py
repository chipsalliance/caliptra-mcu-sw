"""Generate the register modules of registers/generated-firmware.

Each addrmap instantiated in the SoC and MCU address maps becomes one Rust
module, at the address it has in the map. `cargo xtask registers-autogen`
runs this script.

    python peakrdl-tock/scripts/generate_registers.py          # write the files
    python peakrdl-tock/scripts/generate_registers.py --check  # verify they are current
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import tempfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT / "peakrdl-tock" / "src"))

try:
    from systemrdl import RDLCompiler
    from systemrdl.node import AddrmapNode, Node
except ImportError:
    sys.exit(
        "The systemrdl-compiler Python package is required to generate registers.\n"
        "Install it with: pip install systemrdl-compiler"
    )

from peakrdl_tock import TockExporter  # noqa: E402

DEST_DIR = PROJECT_ROOT / "registers" / "generated-firmware" / "src"

RDL_FILES = [
    "hw/caliptra-ss/src/integration/rtl/soc_address_map.rdl",
    "hw/mcu.rdl",
]

# Top-level address maps whose instances are exported.
ADDRESS_MAPS = ["soc", "mcu"]

# Modules of the crate that this script does not generate.
OTHER_MODULES = ["defines", "fuses"]

# Instances that are not exported. The I3C driver takes its base address from
# the memory map, so the second I3C core needs no module of its own.
SKIP_INSTANCES = {"I3CCSR1"}

# Modules that are not exported.
SKIP_MODULES = {"csrng", "hmac", "kv_read", "hmac512", "sha256", "sha512", "spi_host"}

# Modules that only get an address constant. The secondary flash controller
# uses the types of the primary one.
ADDR_ONLY_MODULES = {"secondary_flash_ctrl"}

# Substitutions applied, in order, to the names of the registers, fields and
# blocks instantiated in an RDL file. The firmware and emulator use the
# resulting names.
RENAMES = {
    "target_transaction_interface.rdl": [
        ("QUEUE_THLD_CTRL", "TTI_QUEUE_THLD_CTRL"),
        ("QUEUE_SIZE", "TTI_QUEUE_SIZE"),
        ("IBI_PORT", "TTI_IBI_PORT"),
        ("DATA_BUFFER_THLD_CTRL", "TTI_DATA_BUFFER_THLD_CTRL"),
        ("RESET_CONTROL", "TTI_RESET_CONTROL"),
    ],
    "otp_ctrl.rdl": [
        ("INTERRUPT_ENABLE", "OTP_INTERRUPT_ENABLE"),
        ("STATUS", "OTP_STATUS"),
    ],
}


def rename(node: Node) -> str:
    """The name of a node after the substitutions for its source file."""
    name = node.inst_name
    filename = getattr(node.inst.inst_src_ref, "filename", None) or ""
    for old, new in RENAMES.get(os.path.basename(filename), []):
        name = name.replace(old, new)
    return name


def module_name(inst_name: str) -> str:
    """The Rust module name for an addrmap instance."""
    name = inst_name
    if name.startswith("caliptra_"):
        name = name[len("caliptra_"):]
    if name.endswith(("_reg", "_csr", "_top")):
        name = name[:-4]
    if name.endswith("_ifc"):
        name = name[:-4]
    if name == "I3CCSR":
        name = "i3c"
    return name


def header() -> str:
    """The license and provenance comment for generated files."""
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=PROJECT_ROOT / "hw" / "caliptra-ss",
        capture_output=True,
        text=True,
        check=False,
    )
    lines = ["// Licensed under the Apache-2.0 license.", "//"]
    if result.returncode == 0:
        lines.append(f"// generated by peakrdl-tock with caliptra-ss repo at {result.stdout.strip()}")
    else:
        lines.append("// generated by peakrdl-tock")
    lines.append("//")
    return "\n".join(lines) + "\n"


def generate(extra_files: list[str], extra_addrmap: list[str]) -> dict[str, str]:
    """Generate one module per addrmap instance, and lib.rs.

    Returns the contents of the generated files by file name.
    """
    rdl_files = [str(PROJECT_ROOT / f) for f in RDL_FILES] + extra_files
    tops = list(ADDRESS_MAPS)
    file_header = header()
    exporter = TockExporter()
    files = {}

    with tempfile.TemporaryDirectory() as tmp:
        if extra_addrmap:
            entries = []
            for entry in extra_addrmap:
                typ, sep, addr = entry.partition("@")
                if not sep:
                    sys.exit(f"Invalid addrmap entry: {entry} (should be in the form type@address)")
                entries.append(f"    {typ.strip()} {typ.strip()} @ {addr.strip()};\n")
            extra_rdl = Path(tmp) / "extra.rdl"
            extra_rdl.write_text("addrmap extra {\n" + "".join(entries) + "};\n")
            rdl_files.append(str(extra_rdl))
            tops.append("extra")

        for top in tops:
            rdlc = RDLCompiler()
            for rdl_file in rdl_files:
                rdlc.compile_file(rdl_file)
            root = rdlc.elaborate(top_def_name=top)
            for child in root.top.children():
                if not isinstance(child, AddrmapNode) or child.inst_name in SKIP_INSTANCES:
                    continue
                name = module_name(child.inst_name)
                if name in SKIP_MODULES:
                    continue
                if f"{name}.rs" in files:
                    sys.exit(f"Module {name} is generated by more than one addrmap instance")
                files[f"{name}.rs"] = exporter.export(
                    child,
                    tmp,
                    output_name=name,
                    header=file_header,
                    rename=rename,
                    addr_only=name in ADDR_ONLY_MODULES,
                )

    modules = sorted([Path(f).stem for f in files] + OTHER_MODULES)
    files["lib.rs"] = (
        file_header
        + '#![recursion_limit = "2048"]\n#![no_std]\n'
        + "".join(f"pub mod {name};\n" for name in modules)
    )
    return files


def stale_files(dest: Path, files: dict[str, str]) -> list[str]:
    """The files in dest that differ from the generated ones, or should not exist."""
    kept = {f"{name}.rs" for name in OTHER_MODULES}
    current = {p.name: p.read_text() for p in dest.glob("*.rs") if p.name not in kept}
    return sorted(name for name in files.keys() | current.keys() if files.get(name) != current.get(name))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check that the generated files are current instead of writing them.",
    )
    parser.add_argument(
        "--file",
        action="append",
        default=[],
        help="Extra RDL file to compile. May be given more than once.",
    )
    parser.add_argument(
        "--addrmap",
        action="append",
        default=[],
        help="Extra addrmap instance to export, as type@address. May be given more than once.",
    )
    parser.add_argument(
        "--dest",
        type=Path,
        default=DEST_DIR,
        help="Directory to write to or check. Defaults to registers/generated-firmware/src.",
    )
    args = parser.parse_args()
    dest = args.dest

    files = generate(args.file, args.addrmap)
    stale = stale_files(dest, files)
    if args.check:
        for name in stale:
            print(f"{dest / name} does not match the generator output", file=sys.stderr)
        if stale:
            print('Run "cargo xtask registers-autogen" to update.', file=sys.stderr)
            return 1
        return 0

    dest.mkdir(parents=True, exist_ok=True)
    for name in stale:
        if name in files:
            print(f"Writing to {dest / name}")
            (dest / name).write_text(files[name])
        else:
            print(f"Deleting {dest / name}")
            (dest / name).unlink()
    return 0


if __name__ == "__main__":
    sys.exit(main())
